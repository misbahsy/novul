#!/usr/bin/env bash
# Regenerates THIRD_PARTY_LICENSES.md: the Rust crates and npm packages compiled into NoVul.
# Bundled tools (gitleaks, osv-scanner) and data sources are covered in NOTICE.
set -euo pipefail
cd "$(dirname "$0")/.."

{
  echo "# Third-party licenses"
  echo
  echo "Libraries compiled into NoVul, generated by \`scripts/third-party.sh\`. The bundled gitleaks and"
  echo "osv-scanner binaries and the vulnerability data sources are listed in [NOTICE](NOTICE)."
  echo
  echo "## Rust crates"
  echo
  echo "| Crate | Version | License |"
  echo "|---|---|---|"
  (cd src-tauri && cargo tree -e normal --target aarch64-apple-darwin --prefix none --format '{p}|{l}') |
    grep -v '^novul ' | sed -E 's/ \([^)]*\)//g' | sort -u |
    awk -F'|' '{ split($1, a, " "); printf "| %s | %s | %s |\n", a[1], substr(a[2], 2), ($2 == "" ? "see crate" : $2) }'
  echo
  echo "## npm packages"
  echo
  echo "| Package | Version | License |"
  echo "|---|---|---|"
  for p in svelte @tauri-apps/api @tauri-apps/plugin-dialog $(jq -r '.dependencies // {} | keys[]' node_modules/svelte/package.json); do
    jq -r '"| \(.name) | \(.version) | \(.license // "see package") |"' "node_modules/$p/package.json"
  done | sort -u
} > THIRD_PARTY_LICENSES.md

echo "$(grep -c '^| ' THIRD_PARTY_LICENSES.md) rows written to THIRD_PARTY_LICENSES.md"
